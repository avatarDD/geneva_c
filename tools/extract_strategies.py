#!/usr/bin/env python3
"""
Collects every strategy string from a Geneva checkout (library.py and
tests/*.py) and writes tests/geneva_strategies.h for the parser tests.

    python3 tools/extract_strategies.py /path/to/geneva > tests/geneva_strategies.h

The file is only read, never imported or executed. Strings that Geneva's own
tests expect to be rejected are listed in REJECTED.
"""
import glob
import re
import sys

# Inputs Geneva's tests assert fail to parse (test_parse.py, test_tree.py,
# test_strategy.py), plus "\/ [..]-sleep{1}-|": sleep is outbound-only.
REJECTED = {
    "[]-asdfasdf",
    "[TCP:thing:1]-nooooooope",
    "[TCP:thisdontexist:1]-drop-|",
    "[TCP:]-|",
    "[TCP:flags:0]-foo-|",
    "[TCP:flags:0]-duplicate(,,,)-|",
    "[TCP:flags:0]-duplicate()))-|",
    "[TCP:flags:0]-duplicate(((()-|",
    "[TCP:flags:0]-duplicate(,))))-|",
    "[TCP:flags:0]-drop(duplicate,)-|",
    "[TCP:flags:0]-drop(duplicate,duplicate)-|",
    "[TCP:flags:0]-tamper{TCP:flags:replace:S}(,duplicate)-|",
    "[TCP:flags:0]-tamper{TCP:flags:replace:S}(drop,duplicate)-|",
    "[TCP:flags:R]-duplicate(drop, drop)-| \\/",
    "\\/ [TCP:flags:SA]-sleep{1}-|",
}
# Not strategies: log messages and format strings that happen to match.
SKIP = re.compile(r"Rejecting|%s|\\\"")


def collect(root):
    """Returns [(ok, strategy)] in file order, without duplicates."""
    seen = []
    for path in [root + "/library.py"] + sorted(glob.glob(root + "/tests/*.py")):
        src = open(path, encoding="utf-8").read()
        for m in re.finditer(r'"((?:[^"\\\n]|\\.)*)"', src):
            s = m.group(1)
            looks = "[" in s and ("-|" in s or "\\/" in s or s.endswith(")-") or re.search(r"\]-\w", s))
            if (looks or s.strip() == "\\/") and not SKIP.search(s):
                s = s.replace("\\\\", "\\").strip()
                if s not in seen:
                    seen.append(s)
    return [(s not in REJECTED, s) for s in seen]


def main():
    found = collect(sys.argv[1])
    out = sys.stdout
    out.write("/* Generated by tools/extract_strategies.py from Geneva's library.py and tests. */\n")
    out.write("static const struct { int ok; const char *s; } geneva_strategies[] = {\n")
    for ok, s in found:
        esc = s.replace("\\", "\\\\").replace('"', '\\"')
        out.write('    {%d, "%s"},\n' % (ok, esc))
    out.write("};\n")


if __name__ == "__main__":
    main()
