#!/usr/bin/env python3
"""
Writes src/library_data.h, the built-in strategy library ("geneva library"),
from Geneva's library.py: WORKING_STRATEGIES (found against real censors)
and LAB_STRATEGIES (against the lab censors, see docs/CENSOR.md).

    python3 tools/gen_library.py /path/to/geneva > src/library_data.h

library.py is parsed with ast.literal_eval, never imported or executed.
"""
import ast
import warnings
import sys


def lists(path):
    warnings.simplefilter("ignore", SyntaxWarning)  # "\/" in the strategy strings
    tree = ast.parse(open(path, encoding="utf-8").read(), path)
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            name = getattr(node.targets[0], "id", None)
            if name in ("WORKING_STRATEGIES", "LAB_STRATEGIES"):
                out[name] = ast.literal_eval(node.value)
    return out


def cstr(s):
    s = " ".join(s.split())
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = lists(sys.argv[1] + "/library.py")
    w = sys.stdout.write
    w("/* Generated by tools/gen_library.py from Geneva's library.py\n"
      " * (BSD 3-Clause, Copyright (c) 2020, University of Maryland College Park). */\n")
    w("static const lib_entry lib_entries[] = {\n")
    for e in data["WORKING_STRATEGIES"]:
        w("    {%s, %d, %s, %s, %s, %d, NULL},\n" % (
            cstr(e["strategy"]), round(e["success_rate"] * 100), cstr(e["country"]),
            cstr(e["test_type"]), cstr(e["description"]), 1 if e["server_side"] else 0))
    for e in data["LAB_STRATEGIES"]:
        w("    {%s, 100, \"lab\", \"echo\", %s, 0, %s},\n" % (
            cstr(e["strategy"]), cstr(e["description"]), cstr(" ".join(c.replace("censor", "") for c in e["censors"]))))
    w("};\n")


if __name__ == "__main__":
    main()
