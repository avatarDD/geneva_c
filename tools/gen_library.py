#!/usr/bin/env python3
"""
Writes src/library_data.h, the built-in strategy library ("geneva library"):
the strategies of tools/library.json (found by geneva_c itself against real
censors) and LAB_STRATEGIES of Geneva's library.py (against the lab
censors, see docs/CENSOR.md).

    python3 tools/gen_library.py /path/to/geneva > src/library_data.h

Geneva's WORKING_STRATEGIES (China, India, Kazakhstan, 2019-2020) are not
taken: they no longer work there and never worked in Russia (README,
"Отличия от Geneva"). library.py is parsed with ast.literal_eval, never
imported or executed.
"""
import ast
import json
import os
import warnings
import sys


def lists(path):
    warnings.simplefilter("ignore", SyntaxWarning)  # "\/" in the strategy strings
    tree = ast.parse(open(path, encoding="utf-8").read(), path)
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            name = getattr(node.targets[0], "id", None)
            if name in ("WORKING_STRATEGIES", "LAB_STRATEGIES"):
                out[name] = ast.literal_eval(node.value)
    return out


def cstr(s):
    s = " ".join(s.split())
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = lists(sys.argv[1] + "/library.py")
    own = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "library.json"),
                         encoding="utf-8"))
    w = sys.stdout.write
    w("/* Generated by tools/gen_library.py from tools/library.json and the lab\n"
      " * strategies of Geneva's library.py (BSD 3-Clause, Copyright (c) 2020,\n"
      " * University of Maryland College Park). */\n")
    w("static const lib_entry lib_entries[] = {\n")
    for e in own["strategies"]:
        w("    {%s, %d, %s, %s, %s, 0, NULL, %d},\n" % (
            cstr(e["strategy"]), e["rate"], cstr(own["country"]), cstr(e["test"]),
            cstr(e["description"]), 1 if e["ext"] else 0))
    for e in data["LAB_STRATEGIES"]:
        w("    {%s, 100, \"lab\", \"echo\", %s, 0, %s, 0},\n" % (
            cstr(e["strategy"]), cstr(e["description"]), cstr(" ".join(c.replace("censor", "") for c in e["censors"]))))
    w("};\n")


if __name__ == "__main__":
    main()
